#!/usr/bin/env python3
"""Defect list: where holidays-rs disagrees with the Python `holidays` package.

`holidays` is the mature reference for this domain (0.107, ~200 countries).
This crate covers 19 and reports each holiday on its *observed* date only, so a
naive set difference produces a mountain of false positives: the reference also
lists the raw date of a holiday that was moved ("Christmas Day" and "Christmas
Day (observed)" are two keys). The classification below separates the cases:

  invented  - a date we report that the reference has no holiday for at all.
              A real defect: we are inventing a day off.
  missing   - a reference holiday we do not report, that does NOT fall on a
              Saturday or Sunday. A real gap: a working day we call working.
  weekend   - a reference holiday we do not report that falls at a weekend.
              Cosmetic: the day is already a non-working day.

Run:  python3 research/tools/verify_holidays.py [Country ...] [--years A B]
Needs: pip install holidays
"""

import datetime
import os
import pathlib
import subprocess
import sys

import holidays as pyholidays

ROOT = pathlib.Path(__file__).resolve().parents[2]
CRATE = ROOT / "crates" / "holidays-rs"
CARGO_ENV = {
    **os.environ,
    "PATH": "/workspace/.toolchain/cargo/bin:" + os.environ.get("PATH", ""),
    "CARGO_HOME": "/workspace/.toolchain/cargo",
}

# crate variant -> reference country code. `GB-ENG` means the reference needs
# a subdivision to describe what this crate models (England and Wales).
COUNTRIES = {
    "Indonesia": "ID", "UnitedStates": "US", "UnitedKingdom": "GB-ENG",
    "Germany": "DE", "France": "FR", "Netherlands": "NL", "Spain": "ES",
    "Italy": "IT", "Portugal": "PT", "Belgium": "BE", "Austria": "AT",
    "Poland": "PL", "Sweden": "SE", "Norway": "NO", "Denmark": "DK",
    "Finland": "FI", "Ireland": "IE", "Canada": "CA", "NewZealand": "NZ",
}

EXAMPLE = """//! Generated by research/tools/verify_holidays.py. Do not edit.
use holidays_rs::{Calendar, Country};

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let country = match args[1].as_str() {
__CASES__
        other => panic!("unknown country {other}"),
    };
    let first: i32 = args[2].parse().unwrap();
    let last: i32 = args.get(3).map_or(first, |s| s.parse().unwrap());
    let cal = Calendar::new(country);
    for year in first..=last {
        for (date, name) in cal.holidays_in(year) {
            println!("{date}|{name}");
        }
    }
}
"""


SCRATCH = None


def write_example() -> None:
    """Write the scratch dump example the Rust side is run through."""
    global SCRATCH
    cases = "\n".join(f'        "{n}" => Country::{n},' for n in COUNTRIES)
    (CRATE / "examples").mkdir(exist_ok=True)
    SCRATCH = CRATE / "examples" / "_oracle_names.rs"
    SCRATCH.write_text(EXAMPLE.replace("__CASES__", cases))


def remove_example() -> None:
    if SCRATCH is not None and SCRATCH.exists():
        SCRATCH.unlink()


def our_holidays(country: str, first: int, last: int) -> dict[str, str]:
    r = subprocess.run(
        ["cargo", "run", "--quiet", "--example", "_oracle_names", "--",
         country, str(first), str(last)],
        cwd=CRATE, capture_output=True, text=True, env=CARGO_ENV,
    )
    if r.returncode != 0:
        raise SystemExit(r.stderr[-3000:])
    out = {}
    for line in r.stdout.splitlines():
        if "|" in line:
            d, n = line.split("|", 1)
            out[d.strip()] = n.strip()
    return out


def ref_holidays(code: str, first: int, last: int) -> dict[str, str]:
    years = list(range(first, last + 1))
    if code.endswith("-ENG"):
        cal = pyholidays.country_holidays(code[:-4], subdiv="ENG", years=years)
    else:
        cal = pyholidays.country_holidays(code, years=years)
    return {d.isoformat(): n for d, n in sorted(cal.items())}


def is_weekend(iso: str) -> bool:
    return datetime.date.fromisoformat(iso).weekday() >= 5


def report(country: str, years: list[int]) -> dict[str, list]:
    code = COUNTRIES[country]
    found: dict[str, list] = {"invented": [], "missing": [], "weekend": []}
    first, last = min(years), max(years)
    ours = our_holidays(country, first, last)
    ref = ref_holidays(code, first, last)
    for d in sorted(set(ours) - set(ref)):
        found["invented"].append((d, ours[d]))
    for d in sorted(set(ref) - set(ours)):
        bucket = "weekend" if is_weekend(d) else "missing"
        found[bucket].append((d, ref[d]))
    return found


# Differences that are deliberate, with the reason. A difference not listed
# here is a defect and makes the script exit non-zero, so this file is the
# regression gate for the country tables.
KNOWN_DIFFERENCES = {
    "Indonesia": (
        "The Islamic and Chinese-derived observances (Imlek, Waisak, Idul Fitri, "
        "Idul Adha, Islamic New Year, Maulid, Isra Mikraj, Nyepi) plus ad-hoc "
        "election days are set each year by a joint ministerial decree, not by a "
        "formula, and even the arithmetic Hijri calendar can differ from the "
        "decree by a day. The crate documents them as out of scope and offers "
        "Calendar::with_extra for the published decree."
    ),
    "Spain": (
        "python-holidays drops a national holiday that falls on a Sunday; this "
        "crate keeps it, so 1 November and 6 December still answer is_holiday "
        "true when they are Sundays. Keeping the date is the more useful "
        "behaviour for the domain."
    ),
    "Ireland": (
        "Saint Stephen's Day 2026 falls on a Saturday, so this crate observes it "
        "on Monday 28 December, which is what the Organisation of Working Time "
        "Act provides. python-holidays lists the raw date only."
    ),
    "Canada": (
        "This crate models the federal-wide set, so Victoria Day, Thanksgiving, "
        "Remembrance Day and Boxing Day are always present. python-holidays' "
        "default CA is narrower and exposes some of those only under a "
        "subdivision."
    ),
}


def main() -> int:
    argv = sys.argv[1:]
    years = [2000, 2050]
    if "--years" in argv:
        i = argv.index("--years")
        years = [int(x) for x in argv[i + 1:i + 3]]
        argv = argv[:i]
    only = argv or list(COUNTRIES)
    write_example()

    undocumented = 0
    for country in only:
        f = report(country, years)
        if not (f["invented"] or f["missing"]):
            print(f"ok  {country}")
            continue
        if country in KNOWN_DIFFERENCES:
            print(f"known-difference {country}")
            print(f"      {KNOWN_DIFFERENCES[country]}")
            for d, n in f["invented"]:
                print(f"      invented  {d}  {n}")
            for d, n in f["missing"]:
                print(f"      missing   {d}  {n}")
            continue
        undocumented += 1
        print(f"BUG {country}")
        for d, n in f["invented"]:
            print(f"      invented  {d}  {n}")
        for d, n in f["missing"]:
            print(f"      missing   {d}  {n}")
    print(f"\n{undocumented} undocumented defect(s) out of {len(only)} calendars")
    return 1 if undocumented else 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    finally:
        remove_example()
