#!/usr/bin/env python3
"""Regression gate for `crates/fuzzy-score` against the Python `fuzzywuzzy`.

`fuzzywuzzy` 0.18 is the reference this crate ports, so a difference is a bug in
one of the two. This script generates a scratch Rust example, runs the crate's
scoring functions over a large corpus, and compares every number with the
reference. It exits non-zero on any mismatch.

The corpus is drawn from a seeded xorshift generator, so a failure is
reproducible: the same run fails on the same case.

**The oracle must be the pure-Python `difflib.SequenceMatcher`.** When the
`Levenshtein` package (from `python-Levenshtein`) is importable, `fuzzywuzzy`
silently substitutes a `Levenshtein`-backed matcher that returns *different*
ratios - `36` where `difflib` gives `24` on one two-character case. Any
comparison made in that state is meaningless, so the script refuses to run and
tells you to uninstall it.

Run:  python3 research/tools/verify_fuzzy_score.py [--cases N] [--write-fixture]
Needs: pip install fuzzywuzzy==0.18.0   (and NOT python-Levenshtein)
"""

import argparse
import os
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
CRATE = ROOT / "crates" / "fuzzy-score"
CARGO_ENV = {
    **os.environ,
    "PATH": "/workspace/.toolchain/cargo/bin:" + os.environ.get("PATH", ""),
    "CARGO_HOME": "/workspace/.toolchain/cargo",
}

# The ten functions under test, in fixture column order.
FUNCTIONS = [
    "ratio", "partial_ratio", "token_sort_ratio", "partial_token_sort_ratio",
    "token_set_ratio", "partial_token_set_ratio", "w_ratio", "q_ratio",
    "uw_ratio", "uq_ratio",
]

EXAMPLE = """//! Generated by research/tools/verify_fuzzy_score.py. Do not edit.
use std::io::{self, BufRead, Write};
use fuzzy_score::fuzz;

fn main() {
    let stdin = io::stdin();
    let stdout = io::stdout();
    let mut out = stdout.lock();
    for line in stdin.lock().lines() {
        let line = line.unwrap();
        if line.is_empty() { continue; }
        let mut it = line.splitn(2, '\\t');
        let a = it.next().unwrap_or("");
        let b = it.next().unwrap_or("");
        writeln!(out, "{}\\t{}\\t{}\\t{}\\t{}\\t{}\\t{}\\t{}\\t{}\\t{}",
            fuzz::ratio(a, b),
            fuzz::partial_ratio(a, b),
            fuzz::token_sort_ratio(a, b),
            fuzz::partial_token_sort_ratio(a, b),
            fuzz::token_set_ratio(a, b),
            fuzz::partial_token_set_ratio(a, b),
            fuzz::w_ratio(a, b),
            fuzz::q_ratio(a, b),
            fuzz::uw_ratio(a, b),
            fuzz::uq_ratio(a, b)).unwrap();
    }
}
"""


class Xorshift:
    """The generator the corpus is drawn from, so a failure is reproducible."""

    def __init__(self, seed=0x2545F4914F6CDD1D):
        self.s = seed

    def next(self):
        x = self.s
        x ^= (x << 13) & 0xFFFFFFFFFFFFFFFF
        x ^= x >> 7
        x ^= (x << 17) & 0xFFFFFFFFFFFFFFFF
        self.s = x
        return x

    def below(self, n):
        return self.next() % n


def check_oracle():
    """Refuse to run against a Levenshtein-backed matcher."""
    try:
        import fuzzywuzzy.fuzz as fuzz_module
    except ImportError:
        raise SystemExit("needs: pip install fuzzywuzzy==0.18.0")
    matcher = fuzz_module.SequenceMatcher.__name__
    if matcher != "SequenceMatcher":
        raise SystemExit(
            f"oracle is contaminated: fuzzywuzzy is using {matcher}, not the "
            "pure-Python difflib.SequenceMatcher.\n"
            "Run: pip uninstall -y python-Levenshtein Levenshtein"
        )


def corpus(count):
    """Input pairs: ASCII, a Unicode mix, and long strings for autojunk."""
    rng = Xorshift()
    ascii_pool = list("abc ABC123-_.,!") + ["\t", "\n"]
    uni_pool = (
        list("abcABC 12-_")
        + [chr(c) for c in range(0xC0, 0x100)]
        + [chr(c) for c in range(0x300, 0x310)]
        + ["中", "م", "\u1234", "\u20ac", "\U0001F600", "\u00a0", "\u3000"]
    )

    def make(pool, maxlen):
        return "".join(pool[rng.below(len(pool))] for _ in range(rng.below(maxlen)))

    pairs = []
    for i in range(count):
        pool = ascii_pool if i % 2 == 0 else uni_pool
        pairs.append((make(pool, 28), make(pool, 28)))
    # difflib only applies its popular-element heuristic at 200 elements or
    # more, so short inputs never reach it.
    for _ in range(count // 20):
        a = "".join("abcd"[rng.below(4)] for _ in range(200 + rng.below(200)))
        b = "".join("abcd"[rng.below(4)] for _ in range(200 + rng.below(200)))
        pairs.append((a, b))
    return pairs


def escape(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        elif ord(ch) <= 0xFFFF:
            out.append("\\u%04X" % ord(ch))
        else:
            out.append("\\U%08X" % ord(ch))
    return "".join(out)


def write_example():
    (CRATE / "examples").mkdir(exist_ok=True)
    scratch = CRATE / "examples" / "_oracle_scores.rs"
    scratch.write_text(EXAMPLE)
    return scratch


def rust_scores(pairs, scratch):
    stdin = "".join(
        a.replace("\t", "\x0b").replace("\n", "\x0c")
        + "\t"
        + b.replace("\t", "\x0b").replace("\n", "\x0c")
        + "\n"
        for a, b in pairs
    )
    r = subprocess.run(
        ["cargo", "run", "--quiet", "--example", "_oracle_scores"],
        cwd=CRATE, input=stdin, capture_output=True, text=True, env=CARGO_ENV,
    )
    if r.returncode != 0:
        raise SystemExit(r.stderr[-3000:])
    rows = [line.split("\t") for line in r.stdout.splitlines()]
    if len(rows) != len(pairs):
        raise SystemExit(f"expected {len(pairs)} rows, got {len(rows)}")
    return [[int(x) for x in row] for row in rows]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cases", type=int, default=2000)
    parser.add_argument("--write-fixture", action="store_true")
    args = parser.parse_args()

    check_oracle()
    from fuzzywuzzy import fuzz

    pairs = corpus(args.cases)
    ref = [
        [fn(a, b) for fn in (
            fuzz.ratio, fuzz.partial_ratio, fuzz.token_sort_ratio,
            fuzz.partial_token_sort_ratio, fuzz.token_set_ratio,
            fuzz.partial_token_set_ratio, fuzz.WRatio, fuzz.QRatio,
            fuzz.UWRatio, fuzz.UQRatio,
        )]
        for a, b in pairs
    ]

    if args.write_fixture:
        path = CRATE / "tests" / "fixtures" / "oracle.tsv"
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w") as f:
            f.write("# fuzzywuzzy 0.18 (pure-python difflib) oracle, generated by\n")
            f.write("# research/tools/verify_fuzzy_score.py --write-fixture\n")
            f.write("# a\tb\t" + "\t".join(FUNCTIONS) + "\n")
            for (a, b), scores in zip(pairs, ref):
                f.write(f"{escape(a)}\t{escape(b)}\t" + "\t".join(map(str, scores)) + "\n")
        print(f"wrote {len(pairs)} cases to {path.relative_to(ROOT)}")

    scratch = write_example()
    try:
        got = rust_scores(pairs, scratch)
    finally:
        scratch.unlink()

    mismatches = [0] * len(FUNCTIONS)
    shown = 0
    for (a, b), expected, actual in zip(pairs, ref, got):
        for k in range(len(FUNCTIONS)):
            if expected[k] != actual[k]:
                mismatches[k] += 1
                if shown < 10:
                    shown += 1
                    print(
                        f"  {FUNCTIONS[k]}: expected {expected[k]}, got {actual[k]}"
                        f"  for {a!r} vs {b!r}"
                    )

    print(f"\ncompared {len(pairs)} pairs x {len(FUNCTIONS)} functions")
    for name, count in zip(FUNCTIONS, mismatches):
        status = "ok" if count == 0 else "BUG"
        print(f"  {status:3s} {name:24s} {count} mismatch(es)")
    total = sum(mismatches)
    print(f"\n{total} total mismatch(es)")
    return 1 if total else 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except ImportError as e:
        raise SystemExit(f"needs: pip install fuzzywuzzy==0.18.0 ({e})")
