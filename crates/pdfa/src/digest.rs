//! MD5, for the embedded file checksum.
//!
//! PDF names MD5 for the `/CheckSum` of an attached file, so it is required
//! here. It is an integrity check against accidental corruption, not a
//! signature: an attacker who can edit the attachment can recompute the
//! checksum just as easily. PDF/A pairs it with a real signature when
//! authenticity matters, and that is a separate mechanism this crate does not
//! implement.
//!
//! The implementation is a straight transcription of RFC 1321. It is short
//! enough that a dependency would be larger than the code.

