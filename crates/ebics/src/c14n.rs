//! Canonical XML, as EBICS needs it.
//!
//! An EBICS request is signed over its `header` element, and a signature over
//! XML only means something if both sides agree on the exact bytes. XML
//! Canonicalisation (C14N) is that agreement, and EBICS names it explicitly in
//! the `ds:Reference` transform.
//!
//! # The algorithm, and the one extra step
//!
//! The reference implementations do not use plain exclusive C14N. They use
//! exclusive C14N and then **re-insert the root element's namespace
//! declarations that exclusive canonicalisation dropped**, because exclusive
//! C14N only emits a namespace that the element or an attribute actually uses.
//! The `header` element uses no `ds:` prefix of its own, so `xmlns:ds` vanishes
//! from its canonical form — and the digest that a bank computes, and the one
//! the reference clients compute, still includes it.
//!
//! This is not a guess. It is what both open reference implementations do:
//! `node-ebics-client` and `ebics-client-php` each canonicalise exclusively and
//! then inject the missing in-scope declarations. It is checked here against a
//! request generated by the former, whose own digest only reproduces when the
//! injection is performed. See the tests in `tests/c14n_oracle.rs`.
//!
//! # What is not implemented
//!
//! This handles the shapes an EBICS message contains: elements, attributes,
//! text, no comments, no processing instructions, UTF-8 only. That is the whole
//! of what the protocol produces, and implementing the general recommendation
//! would mean handling encodings and constructs no bank sends.

use xmlkit::{Element, Node};

/// The XML namespace URI that carries a namespace declaration.
/// Canonicalises `element` for an EBICS digest.
///
/// The result is exclusive C14N with the root's unused namespace declarations
/// re-inserted, which is what the reference clients compute.
#[must_use]
pub fn canonicalize(element: &Element) -> String {
    canonicalize_with_root_namespaces(element, &root_namespaces(element))
}

/// Canonicalises `target`, taking the in-scope declarations from `document_root`.
///
/// This is the form an EBICS caller wants: the digest covers the `header`
/// element, but the declarations it must include are the ones on the request
/// root, which is an ancestor. Passing the root explicitly is what makes the
/// injection possible for a detached subtree.
#[must_use]
pub fn canonicalize_in_document(document_root: &Element, target: &Element) -> String {
    canonicalize_with_root_namespaces(target, &root_namespaces(document_root))
}

/// Canonicalises `element`, re-inserting any of `in_scope` that exclusive
/// canonicalisation would drop.
///
/// `in_scope` is the namespace declarations of the document root, in document
/// order. Callers that canonicalise a detached element can pass what they know;
/// [`canonicalize`] reads them from the element itself.
#[must_use]
pub fn canonicalize_with_root_namespaces(
    element: &Element,
    in_scope: &[(String, String)],
) -> String {
    let mut out = String::new();
    write_element(&mut out, element, true, in_scope);
    out
}

/// The namespace declarations visible at `element`, in document order.
///
/// xmlkit's [`Element`] keeps the prefix inside the name and does not carry a
/// separate namespace table, so the declarations are the attributes whose name
/// is `xmlns` or starts with `xmlns:`.
#[must_use]
pub fn root_namespaces(element: &Element) -> Vec<(String, String)> {
    let mut out: Vec<(String, String)> = element
        .attributes
        .iter()
        .filter_map(|(name, value)| {
            if name == "xmlns" {
                Some((String::new(), value.clone()))
            } else {
                name.strip_prefix("xmlns:")
                    .map(|prefix| (prefix.to_owned(), value.clone()))
            }
        })
        .collect();
    // xmlkit keeps attributes in a `BTreeMap`, so `xmlns:ds` sorts before
    // `xmlns`; C14N emits the default declaration first.
    out.sort_by(|left, right| {
        left.0
            .is_empty()
            .cmp(&right.0.is_empty())
            .reverse()
            .then_with(|| left.0.cmp(&right.0))
    });
    out
}

/// Writes one element in canonical form.
///
/// `is_root` marks the element the digest covers: only it receives the injected
/// declarations, because the injection models what a verifier in document
/// context would see at the top of the node-set.
fn write_element(
    out: &mut String,
    element: &Element,
    is_root: bool,
    in_scope: &[(String, String)],
) {
    out.push('<');
    out.push_str(&element.name);

    // A namespace declaration is an attribute in xmlkit's model, and C14N sorts
    // attributes by name with namespace declarations first. The declarations the
    // element already carries, plus, at the root, the in-scope ones it is
    // missing, are merged so the sort sees one set.
    let mut declarations: Vec<(String, String)> = Vec::new();
    let mut plain: Vec<(&str, &str)> = Vec::new();
    for (name, value) in &element.attributes {
        if name == "xmlns" {
            declarations.push((String::new(), value.clone()));
        } else if let Some(prefix) = name.strip_prefix("xmlns:") {
            declarations.push((prefix.to_owned(), value.clone()));
        } else {
            plain.push((name, value));
        }
    }

    if is_root {
        for (prefix, uri) in in_scope {
            if !declarations.iter().any(|(present, _)| present == prefix) {
                declarations.push((prefix.clone(), uri.clone()));
            }
        }
    }

    // The default declaration comes before the prefixed ones, which are sorted
    // by prefix.
    declarations.sort_by(
        |left, right| match (left.0.is_empty(), right.0.is_empty()) {
            (true, false) => std::cmp::Ordering::Less,
            (false, true) => std::cmp::Ordering::Greater,
            _ => left.0.cmp(&right.0),
        },
    );

    for (prefix, uri) in &declarations {
        out.push(' ');
        if prefix.is_empty() {
            out.push_str("xmlns");
        } else {
            out.push_str("xmlns:");
            out.push_str(prefix);
        }
        out.push_str("=\"");
        escape_attribute_into(out, uri);
        out.push('"');
    }

    // The remaining attributes, sorted by their qualified name. xmlkit already
    // keeps them in a `BTreeMap`, so iteration is that order.
    for (name, value) in plain {
        out.push(' ');
        out.push_str(name);
        out.push_str("=\"");
        escape_attribute_into(out, value);
        out.push('"');
    }

    if element.children.is_empty() {
        out.push_str("></");
        out.push_str(&element.name);
        out.push('>');
        return;
    }

    out.push('>');
    for child in &element.children {
        match child {
            Node::Element(child) => write_element(out, child, false, &[]),
            Node::Text(text) => escape_text_into(out, text),
            // Comments are stripped by the digest transform, so they are not
            // written. `ds:Reference` in an EBICS message never asks for them.
            Node::Comment(_) => {}
        }
    }
    out.push_str("</");
    out.push_str(&element.name);
    out.push('>');
}

/// Escapes text content the way C14N specifies.
fn escape_text_into(out: &mut String, text: &str) {
    for character in text.chars() {
        match character {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '\r' => out.push_str("&#xD;"),
            other => out.push(other),
        }
    }
}

/// Escapes an attribute value the way C14N specifies.
fn escape_attribute_into(out: &mut String, value: &str) {
    for character in value.chars() {
        match character {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '"' => out.push_str("&quot;"),
            '\t' => out.push_str("&#x9;"),
            '\n' => out.push_str("&#xA;"),
            '\r' => out.push_str("&#xD;"),
            other => out.push(other),
        }
    }
}

/// The namespace URI reserved for namespace declarations, exposed so a caller
/// can tell a declaration from a normal attribute.
#[must_use]
pub fn is_namespace_declaration(name: &str) -> bool {
    name == "xmlns" || name.starts_with("xmlns:")
}

#[cfg(test)]
mod tests {
    use super::{
        canonicalize, canonicalize_in_document, is_namespace_declaration, root_namespaces,
    };
    use xmlkit::parse;

    #[test]
    fn declarations_are_recognised() {
        assert!(is_namespace_declaration("xmlns"));
        assert!(is_namespace_declaration("xmlns:ds"));
        assert!(!is_namespace_declaration("authenticate"));
    }

    #[test]
    fn root_namespaces_are_in_document_order() {
        let element =
            parse(r#"<a xmlns="urn:x" xmlns:ds="urn:d" xmlns:xsi="urn:s"/>"#).expect("parses");
        let namespaces = root_namespaces(&element);
        assert_eq!(
            namespaces,
            vec![
                (String::new(), "urn:x".to_owned()),
                ("ds".to_owned(), "urn:d".to_owned()),
                ("xsi".to_owned(), "urn:s".to_owned()),
            ]
        );
    }

    /// An element with no attributes and no children is written as an open and
    /// close tag, not as a self-closing one: C14N forbids the short form.
    #[test]
    fn empty_elements_are_expanded() {
        let element = parse("<a/>").expect("parses");
        assert_eq!(canonicalize(&element), "<a></a>");
    }

    /// The root receives the in-scope declarations it does not use, which is the
    /// whole reason this module exists.
    #[test]
    fn the_root_receives_unused_declarations() {
        let document = parse(
            r#"<ebicsRequest xmlns="urn:org:ebics:H004" xmlns:ds="http://www.w3.org/2000/09/xmldsig#"><header authenticate="true"/></ebicsRequest>"#,
        )
        .expect("parses");
        let header = document
            .children
            .iter()
            .find_map(|node| match node {
                xmlkit::Node::Element(element) => Some(element.clone()),
                _ => None,
            })
            .expect("header present");

        // The header uses no `ds` prefix, so exclusive C14N alone would drop it.
        let canonical = canonicalize_in_document(&document, &header);
        assert!(
            canonical.contains("xmlns:ds=\"http://www.w3.org/2000/09/xmldsig#\""),
            "got {canonical}"
        );
    }

    /// Text is escaped, and the escaping is C14N's, not the XML default: `>` is
    /// escaped and a carriage return becomes a character reference.
    #[test]
    fn text_is_escaped() {
        let element = parse("<a>x &lt; y &gt; z</a>").expect("parses");
        assert_eq!(canonicalize(&element), "<a>x &lt; y &gt; z</a>");
    }
}
